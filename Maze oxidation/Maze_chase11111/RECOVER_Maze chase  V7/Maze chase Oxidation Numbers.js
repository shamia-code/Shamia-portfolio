		function rectsOverlap(a, b) {
		  return (
		    a.x < b.x + b.width &&
		    a.x + a.width > b.x &&
		    a.y < b.y + b.height &&
		    a.y + a.height > b.y
		  );
		}
		
		function isCollidingWithAnyWall(nx, ny) {
		  const avatarRect = getAvatarRectAt(nx, ny);
		  if (!avatarRect) return false;
		
		  for (let i = 0; i < wallData.length; i++) {
		    const wallRect = getWallRect(wallData[i]);
		    if (rectsOverlap(avatarRect, wallRect)) {
		      return true;
		    }
		  }
		
		  return false;
		}
		
