		function bringDisplayObjectToFront(obj) {
		  if (!obj || !obj.parent || !obj.parent.setChildIndex) return;
		  obj.parent.setChildIndex(obj, obj.parent.numChildren - 1);
		}
		
		function bringDescendantBranchToFront(root, obj) {
		  if (!root || !obj) return;
		
		  let current = obj;
		  while (current && current !== root) {
		    bringDisplayObjectToFront(current);
		    current = current.parent;
		  }
		}
		
		function sendLikelyOptionBackgroundsBack(optionClip) {
		  if (!optionClip?.children || !optionClip.setChildIndex) return;
		
		  const likelyBackgrounds = optionClip.children.filter(child => {
		    const name = String(child?.name || "").toLowerCase();
		    return name.includes("bg") ||
		      name.includes("background") ||
		      name.includes("backing") ||
		      name.includes("rect") ||
		      name.includes("rectangle");
		  });
		
		  likelyBackgrounds.reverse().forEach(child => {
		    optionClip.setChildIndex(child, 0);
		  });
		}
		
		function normalizeOptionLayering(opt, optionClip, currentQuestionIndex) {
		  if (!optionClip) return;
		
		  sendLikelyOptionBackgroundsBack(optionClip);
		
		  for (let i = 0; i <= questions.length; i++) {
		    const visualClip = getVisualClip(opt, i);
		    if (visualClip && (i === currentQuestionIndex || visualClip.visible !== false)) {
		      bringDescendantBranchToFront(optionClip, visualClip);
		    }
		  }
		
		  const labelField = findOptionLabelField(optionClip);
		  bringDescendantBranchToFront(optionClip, labelField);
		}
		
