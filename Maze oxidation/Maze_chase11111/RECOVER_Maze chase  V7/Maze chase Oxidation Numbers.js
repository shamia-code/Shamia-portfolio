		function showQuestion(idx, cpID) {
		  gameState = "QUESTION";
		  questionLocked = false;
		  stopMoving();
		  answerCollisionArmed = false;
		  // ---- FIX: clear all contact locks so wrong-answer re-entry always works ----
		  optionContactLocks.clear();
		  const q = questions[idx];
		  questionPanel.visible = true;
		  //if (questionPanel.qText) questionPanel.qText.text = q.q;
		  if (questionPanel.qText) {
		        const qText = questionPanel.qText;
		
		        // ── Store original values on first run only ──────────────────────────
		        // Ignore a first-frame scale under 1 so auto-start does not lock in
		        // a tiny/soft transform and make the large question look blurry.
		        if (qText._originY == null) {
		            const liveSX = qText.scaleX != null ? qText.scaleX : 1;
		            const liveSY = qText.scaleY != null ? qText.scaleY : 1;
		            qText._originY  = qText.y;
		            qText._originSX = liveSX >= 0.9 ? liveSX : 1;
		            qText._originSY = liveSY >= 0.9 ? liveSY : 1;
		            qText._originLineWidth = Number(qText.lineWidth) > 0 ? Number(qText.lineWidth) : 794;
		        }
		
		        const originY  = qText._originY;
		        const originSX = qText._originSX;
		        const originSY = qText._originSY;
		        const originLineWidth = qText._originLineWidth;
		        const smallSX  = originSX * 0.55;
		        const smallSY  = originSY * 0.55;
		        const compactLineWidth = 1400;
		
		        // ── HARD RESET everything first ───────────────────────────────────────
		        createjs.Tween.removeTweens(qText);
		        if (qText.uncache) qText.uncache();
		        qText.visible = true;
		        qText.alpha   = 1;
		        qText.y       = originY;
		        qText.scaleX  = originSX;
		        qText.scaleY  = originSY;
		        qText.lineWidth = originLineWidth;
		        qText.text    = q.q;
		        if (qText.cache) {
		            const twCache = qText.getMeasuredWidth  ? qText.getMeasuredWidth()  : 800;
		            const thCache = qText.getMeasuredHeight ? qText.getMeasuredHeight() : 80;
		            const align = qText.textAlign || "left";
		            const baseX = align === "center" ? -twCache / 2 : align === "right" ? -twCache : 0;
		            qText.cache(baseX - 12, -12, twCache + 24, thCache + 24, 2);
		        }
		
		        // ── Build / reuse background Shape ───────────────────────────────────
		        if (!qText._bgShape) {
		            const bg = new createjs.Shape();
		            bg.name         = "qTextBg";
		            bg.mouseEnabled = false;
		            const parent = qText.parent || questionPanel;
		            parent.addChildAt(bg, Math.max(0, parent.getChildIndex(qText)));
		            qText._bgShape = bg;
		        }
		
		        const bg   = qText._bgShape;
		        const padX = 30;
		        const padY = 150;
		        const tw   = qText.getMeasuredWidth  ? qText.getMeasuredWidth()  : 220;
		        const th   = qText.getMeasuredHeight ? qText.getMeasuredHeight() : 28;
		        const bgW  = tw + padX * 2;
		        const bgH  = th + padY * 2;
		        const bgX  = qText.x - bgW / 2;
		        const bgY  = qText.y - padY;
		
		        // ── Hard reset bg ─────────────────────────────────────────────────────
		        createjs.Tween.removeTweens(bg);
		        bg.x       = 0;
		        bg.y       = 0;
		        bg.alpha   = 1;
		        bg.visible = true;
		
		        bg.graphics
		            .clear()
		            .setStrokeStyle(1.5)
		            .beginStroke("rgba(91, 98, 105, 0.8)")
		            .beginFill("rgba(10,20,50,0.94)")
		            .drawRoundRect(bgX, bgY, bgW, bgH, 10)
		            .endFill()
		            .endStroke();
		
		        // ── Full sequence ─────────────────────────────────────────────────────
		        createjs.Tween.get(qText)
		            .wait(3000)
		            // Step 3: drop and fade out
		            .to({ y: originY + 350, alpha: 0 }, 500, createjs.Ease.sineIn)
		            // Step 4: snap invisibly to lower position, small scale
		            .call(() => {
		            if (qText.uncache) qText.uncache();
		            qText.y      = originY + 240;
		            qText.scaleX = smallSX;
		            qText.scaleY = smallSY;
		            qText.lineWidth = compactLineWidth;
		            qText.alpha  = 0;
		            })
		            // Step 5: rise up and fade in as small text
		            .to({ y: originY + 300, alpha: 1 }, 480, createjs.Ease.sineOut);
		            // Step 6: stays wider at the original vertical position
		
		        // Background fades out with the drop, stays hidden during small text
		        createjs.Tween.get(bg)
		            .wait(3000)
		            .to({ alpha: 0 }, 500, createjs.Ease.sineIn)
		            .call(() => {
		            bg.visible = false;
		            bg.alpha   = 1;  // reset alpha ready for next question
		            });
		    }
		  questionPanel.qIndex = idx;
		  questionPanel.cpID   = cpID;
		  setQuestionOptionTexts(q);
		  enableAllOptions();
		  resetAllOptionVisuals();
		  hideAllLegacyAnswerVisuals();
		  updateFeedbackDisplay(INITIAL_FEEDBACK_TEXT, null);
		  updateLivesDisplay();
		  playQuestionAudio(idx);
		}
		
