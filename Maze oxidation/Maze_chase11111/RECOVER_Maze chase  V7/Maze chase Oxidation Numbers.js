		// Search: direct child of option → named descendant of option →
		//         direct child of questionPanel → named descendant of questionPanel →
		//         direct child of stageRoot → named descendant of stageRoot
		function getAnswerBall(index) {
		  const ballName   = getBallNameForAnswerIndex(index);
		  const optionClip = getAnswerOption(index);
		
		  if (optionClip?.[ballName])                              return optionClip[ballName];
		  const fromOption = getNamedDescendantByExactName(optionClip, ballName);
		  if (fromOption)                                          return fromOption;
		  if (questionPanel?.[ballName])                           return questionPanel[ballName];
		  const fromPanel = getNamedDescendantByExactName(questionPanel, ballName);
		  if (fromPanel)                                           return fromPanel;
		  if (stageRoot?.[ballName])                               return stageRoot[ballName];
		  return getNamedDescendantByExactName(stageRoot, ballName) ?? null;
		}
		
