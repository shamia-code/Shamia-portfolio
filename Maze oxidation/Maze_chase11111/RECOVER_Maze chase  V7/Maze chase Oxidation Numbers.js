		function getClipDurationMs(clip) {
		  if (!clip) return 0;
		
		  if (clip.htmlElement?.duration && isFinite(clip.htmlElement.duration)) {
		    return clip.htmlElement.duration * 1000;
		  }
		
		  const totalFrames = Number(clip.totalFrames) || 0;
		  const fps = Number(clip.framerate) || Number(stageRoot.framerate) || Number(createjs.Ticker?.framerate) || 24;
		  if (totalFrames > 0 && fps > 0) {
		    return (totalFrames / fps) * 1000;
		  }
		
		  return 0;
		}
		
		function collectNamedDescendants(container, results, seen) {
		  if (!container || !container.children) return;
		
		  container.children.forEach(child => {
		    if (!child || seen.has(child)) return;
		    seen.add(child);
		
		    if (child.name) {
		      results.push(child);
		    }
		
		    if (child.children && child.children.length) {
		      collectNamedDescendants(child, results, seen);
		    }
		  });
		}
		
		function getFirstAvailableClip(names) {
		  for (let i = 0; i < names.length; i++) {
		    const directClip = stageRoot[names[i]];
		    if (directClip) return directClip;
		  }
		
		  const namedChildren = [];
		  collectNamedDescendants(stageRoot, namedChildren, new Set());
		
		  for (let i = 0; i < names.length; i++) {
		    const target = String(names[i]).toLowerCase();
		
		    const exactMatch = namedChildren.find(child => String(child.name).toLowerCase() === target);
		    if (exactMatch) return exactMatch;
		
		    const partialMatch = namedChildren.find(child => String(child.name).toLowerCase().includes(target));
		    if (partialMatch) return partialMatch;
		  }
		
		  return null;
		}
		
