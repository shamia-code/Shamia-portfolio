		function getRect(obj) {
		  if (!obj) return null;
		  const tb = obj.getTransformedBounds ? obj.getTransformedBounds() : null;
		  if (tb) return tb;
		  const b = obj.getBounds ? obj.getBounds() : null;
		  const w = obj.hitW || (b ? b.width  : 40);
		  const h = obj.hitH || (b ? b.height : 40);
		  return { x: obj.x, y: obj.y, width: w, height: h };
		}
		
		function objectsOverlap(a, b) {
		  if (!a || !b) return false;
		  const ar = getRect(a);
		  const br = getRect(b);
		  if (!ar || !br) return false;
		  const acx = ar.x + ar.width  / 2;
		  const acy = ar.y + ar.height / 2;
		  const bcx = br.x + br.width  / 2;
		  const bcy = br.y + br.height / 2;
		  const threshold = Math.min(ar.width, ar.height, br.width, br.height) * 0.55;
		  return Math.sqrt(Math.pow(acx - bcx, 2) + Math.pow(acy - bcy, 2)) < threshold;
		}
		
		function getGlobalDisplayRect(obj) {
		  if (!obj) return null;
		
		  const bounds = obj.getBounds ? obj.getBounds() : null;
		  if (bounds && obj.localToGlobal) {
		    const p1 = obj.localToGlobal(bounds.x, bounds.y);
		    const p2 = obj.localToGlobal(bounds.x + bounds.width, bounds.y);
		    const p3 = obj.localToGlobal(bounds.x + bounds.width, bounds.y + bounds.height);
		    const p4 = obj.localToGlobal(bounds.x, bounds.y + bounds.height);
		    const xs = [p1.x, p2.x, p3.x, p4.x];
		    const ys = [p1.y, p2.y, p3.y, p4.y];
		    return {
		      x: Math.min(...xs),
		      y: Math.min(...ys),
		      width: Math.max(...xs) - Math.min(...xs),
		      height: Math.max(...ys) - Math.min(...ys)
		    };
		  }
		
		  if (obj.children && obj.children.length) {
		    const childRects = obj.children
		      .filter(child => child && child.visible !== false)
		      .map(getGlobalDisplayRect)
		      .filter(Boolean);
		
		    if (childRects.length) {
		      const minX = Math.min(...childRects.map(rect => rect.x));
		      const minY = Math.min(...childRects.map(rect => rect.y));
		      const maxX = Math.max(...childRects.map(rect => rect.x + rect.width));
		      const maxY = Math.max(...childRects.map(rect => rect.y + rect.height));
		      return { x: minX, y: minY, width: maxX - minX, height: maxY - minY };
		    }
		  }
		
		  const fallback = getRect(obj);
		  if (fallback && obj.localToGlobal) {
		    const point = obj.localToGlobal(0, 0);
		    if (point) {
		      return {
		        x: point.x,
		        y: point.y,
		        width: fallback.width,
		        height: fallback.height
		      };
		    }
		  }
		
		  const transformed = obj.getTransformedBounds ? obj.getTransformedBounds() : null;
		  if (transformed) return transformed;
		
		  return fallback;
		}
		
