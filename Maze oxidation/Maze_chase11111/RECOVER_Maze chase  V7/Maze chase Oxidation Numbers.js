		function findCongratulationTextField(container) {
		  if (!container) return null;
		
		  const directNames = [
		    "congratulation_txt",
		    "congratulations_txt",
		    "congratulationTxt",
		    "congratulationText",
		    "congrats_txt",
		    "txt"
		  ];
		
		  for (let i = 0; i < directNames.length; i++) {
		    if (container[directNames[i]]) return container[directNames[i]];
		  }
		
		  const named = [];
		  collectNamedDescendants(container, named, new Set());
		  const byName = named.find(child => {
		    const name = String(child?.name || "").toLowerCase();
		    return name === "congratulation_txt" ||
		      name === "congratulations_txt" ||
		      name.indexOf("congratulation_txt") !== -1 ||
		      name.indexOf("congrat") !== -1 && name.indexOf("txt") !== -1;
		  });
		  if (byName) return byName;
		
		  return findFirstNonVisualTextDescendant(container);
		}
		
		function revealCongratulationText(field, message) {
		  if (!field) return false;
		
		  let current = field;
		  while (current) {
		    current.visible = true;
		    current.alpha = 1;
		    current = current.parent;
		  }
		
		  setDisplayText(field, message);
		  if (field.text !== undefined) field.text = message;
		
		  const nested = [];
		  collectNamedDescendants(field, nested, new Set());
		  nested.forEach(child => {
		    if (child && child.text !== undefined) child.text = message;
		    if (child) {
		      child.visible = true;
		      child.alpha = 1;
		    }
		  });
		
		  bringDisplayObjectToFront(field);
		  return true;
		}
		
