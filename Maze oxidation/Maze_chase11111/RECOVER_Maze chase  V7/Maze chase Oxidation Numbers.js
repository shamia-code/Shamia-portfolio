		// ====================== CHECKPOINT COLLISION ======================
		function checkCheckpointCollision() {
		  if (gameState !== "PLAYING" || checkpointCooldown) return;
		  const cp = checkpoints[currentCheckpointIndex];
		  if (!cp || !cp.clip || answered.has(cp.id)) return;
		  if (objectsOverlap(avatar, cp.clip)) {
		    if (lastTriggeredCP !== cp.id) { lastTriggeredCP = cp.id; showQuestion(cp.qIndex, cp.id); }
		  } else {
		    if (lastTriggeredCP === cp.id) lastTriggeredCP = null;
		  }
		}
		
		function checkExitCollision() {
		  if (answered.size >= questions.length && objectsOverlap(avatar, exitZone)) {
		    gameState = "WIN";
		    if (timerInterval) clearInterval(timerInterval);
		    if (moveInterval)  clearInterval(moveInterval);
		    triggerWin();
		  }
		}
		
