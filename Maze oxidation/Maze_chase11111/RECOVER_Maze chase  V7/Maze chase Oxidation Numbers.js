		function checkAnswerCollision() {
		  if (gameState !== "QUESTION" || questionLocked || !questionPanel?.visible) {
		    return;
		  }
		  refreshAnswerContactLocks();
		
		  const touchingAnyOption = OPTION_NAMES.some((opt, index) => optionOverlapsAvatar(getAnswerOption(index), index));
		  if (!answerCollisionArmed) {
		    if (!touchingAnyOption) {
		      answerCollisionArmed = true;
		    } else {
		      return;
		    }
		  }
		
		  for (let i = 0; i < OPTION_NAMES.length; i++) {
		    if (optionContactLocks.has(i)) continue;
		    const optionClip = getAnswerOption(i);
		    if (!optionOverlapsAvatar(optionClip, i)) continue;
		    optionContactLocks.add(i);
		    handleAnswer(i);
		    return;
		  }
		}
		
