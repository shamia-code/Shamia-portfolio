		function shakeDisplayObject(obj, duration = 520, strength = 7) {
		  if (!obj) return;
		  const startX = obj.x;
		  const startY = obj.y;
		  createjs.Tween.removeTweens(obj);
		  createjs.Tween.get(obj)
		    .to({ x: startX - strength, y: startY + 2 }, 55)
		    .to({ x: startX + strength, y: startY - 2 }, 55)
		    .to({ x: startX - strength * 0.75, y: startY - 1 }, 55)
		    .to({ x: startX + strength * 0.75, y: startY + 1 }, 55)
		    .to({ x: startX - strength * 0.45, y: startY + 1 }, 55)
		    .to({ x: startX + strength * 0.45, y: startY - 1 }, 55)
		    .to({ x: startX, y: startY }, Math.max(80, duration - 330), createjs.Ease.sineOut);
		}
		
