		// Maps option index (0–3) to ball name for the current question.
		// Correct answer index → the randomly assigned correct ball for this run.
		// Wrong answer indices → remaining BALL_NAMES in order, skipping the correct ball.
		function getBallNameForAnswerIndex(index) {
		  const qIndex = questionPanel?.qIndex ?? 0;
		  const question = questions[qIndex];
		  if (!question) return BALL_NAMES[index];
		
		  const correctBall = correctBallByQuestion[qIndex] || BALL_NAMES[question.c];
		
		  if (index === question.c) return correctBall;
		
		  // Distribute remaining balls across wrong-answer slots in BALL_NAMES order
		  const wrongBalls   = BALL_NAMES.filter(b => b !== correctBall);
		  const wrongIndexes = [0, 1, 2, 3].filter(i => i !== question.c);
		  const pos          = wrongIndexes.indexOf(index);
		  return wrongBalls[pos] ?? BALL_NAMES[index];
		}
		
