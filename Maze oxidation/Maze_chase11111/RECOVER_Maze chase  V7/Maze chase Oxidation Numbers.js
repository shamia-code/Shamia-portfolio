		function buildGrieverPathData() {
		  const pathClips = [];
		  const seen = new Set();
		
		  // Collect p1...p35 directly from timeline properties
		  for (let i = 1; i <= 35; i++) {
		    const key = "p" + i;
		    const clip = stageRoot[key];
		    if (clip && !seen.has(clip)) {
		      clip._pathId = key;
		      seen.add(clip);
		      pathClips.push(clip);
		    }
		  }
		
		  // Also sweep named descendants in case paths are nested
		  const descendants = [];
		  collectNamedDescendants(stageRoot, descendants, new Set());
		  descendants.forEach(clip => {
		    if (!clip || seen.has(clip)) return;
		    if (/^p\d+$/i.test(String(clip.name || ""))) {
		      clip._pathId = clip.name;
		      seen.add(clip);
		      pathClips.push(clip);
		    }
		  });
		
		  grieverPaths = pathClips
		    .map(clip => {
		      let rect = null;
		
		      // 1. Full global transform (best — accounts for parent scaling/rotation)
		      const gb = clip.getTransformedBounds ? clip.getTransformedBounds() : null;
		      if (gb && gb.width > 0 && gb.height > 0) {
		        rect = { x: gb.x, y: gb.y, width: gb.width, height: gb.height };
		      }
		
		      // 2. Local bounds + clip position (works when parents are identity transforms)
		      if (!rect) {
		        const lb = clip.getBounds ? clip.getBounds() : null;
		        if (lb && lb.width > 0 && lb.height > 0) {
		          rect = { x: clip.x + lb.x, y: clip.y + lb.y,
		                   width: lb.width, height: lb.height };
		        }
		      }
		
		      // 3. Last resort: use clip.x/y with hitW/hitH or a default size
		      if (!rect) {
		        const w = clip.hitW || clip.width || 40;
		        const h = clip.hitH || clip.height || 40;
		        rect = { x: clip.x, y: clip.y, width: w, height: h };
		      }
		
		      if (!rect || rect.width <= 0 || rect.height <= 0) {
		        return null;
		      }
		
		      return {
		        id:   clip._pathId || clip.name || "(unnamed path)",
		        clip,
		        rect,
		        axis: rect.width >= rect.height ? "x" : "y"
		      };
		    })
		    .filter(Boolean)
		    .sort((a, b) => {
		      const aNum = parseInt(String(a.id).replace(/\D+/g, ""), 10) || 0;
		      const bNum = parseInt(String(b.id).replace(/\D+/g, ""), 10) || 0;
		      return aNum - bNum;
		    });
		}
		
		function pointInRect(point, rect, pad = 0) {
		  return !!point && !!rect &&
		    point.x >= rect.x - pad &&
		    point.x <= rect.x + rect.width + pad &&
		    point.y >= rect.y - pad &&
		    point.y <= rect.y + rect.height + pad;
		}
		
		function getObjectCenter(obj) {
		  const rect = getRect(obj);
		  if (!rect) return { x: obj?.x || 0, y: obj?.y || 0 };
		  return {
		    x: rect.x + rect.width / 2,
		    y: rect.y + rect.height / 2
		  };
		}
		
		function getGrieverRectAt(griever, nx, ny) {
		  const rect = getRect(griever);
		  if (!rect) return null;
		  return {
		    x: rect.x + (nx - griever.x),
		    y: rect.y + (ny - griever.y),
		    width: rect.width,
		    height: rect.height
		  };
		}
		
		function shrinkRect(rect, amount) {
		  if (!rect) return null;
		  return {
		    x: rect.x + amount,
		    y: rect.y + amount,
		    width: Math.max(1, rect.width - amount * 2),
		    height: Math.max(1, rect.height - amount * 2)
		  };
		}
		
		function getGrieverCollisionRectAt(griever, nx, ny) {
		  return shrinkRect(getGrieverRectAt(griever, nx, ny), 3);
		}
		
		function getBlockingGrieverAt(griever, nx, ny) {
		  const grieverRect = getGrieverCollisionRectAt(griever, nx, ny);
		  if (!grieverRect) return null;
		
		  for (let i = 0; i < grievers.length; i++) {
		    const other = grievers[i];
		    if (!other || other === griever || other.visible === false) continue;
		    const otherRect = getGrieverCollisionRectAt(other, other.x, other.y);
		    if (otherRect && rectsOverlap(grieverRect, otherRect)) return other;
		  }
		
		  return null;
		}
		
		function reversePathState(state, fromCollision = false) {
		  if (!state) return;
		  state.direction *= -1;
		  state.samePathReversals = (state.samePathReversals || 0) + 1;
		  if (state.samePathReversals >= GRIEVER_SAME_PATH_REVERSAL_LIMIT) {
		    state.forceDiversion = true;
		  }
		  if (fromCollision) {
		    state.collisionRetreatTicks = GRIEVER_COLLISION_RETREAT_TICKS;
		    state.forcedReturnPath = state.previousPath || state.lastPath || null;
		  }
		}
		
		function reverseGrieverDirection(griever) {
		  if (!griever) return;
		
		  const tick = createjs.Ticker?.getTicks ? createjs.Ticker.getTicks() : Date.now();
		  if (grieverReverseTicks.get(griever) === tick) return;
		  grieverReverseTicks.set(griever, tick);
		
		  const state = grieverPathStates.get(griever);
		  if (state) {
		    reversePathState(state, true);
		  }
		
		  const direction = grieverDirections.get(griever);
		  if (direction) {
		    direction.x *= -1;
		    direction.y *= -1;
		    direction.turnsUntilChange = Math.max(direction.turnsUntilChange || 0, 12);
		    direction.collisionRetreatTicks = GRIEVER_COLLISION_RETREAT_TICKS;
		  }
		}
		
		function canPlaceGrieverIgnoringPeers(griever, nx, ny) {
		  const grieverRect = getGrieverCollisionRectAt(griever, nx, ny);
		  if (!grieverRect) return false;
		
		  for (let i = 0; i < wallData.length; i++) {
		    if (rectsOverlap(grieverRect, getWallRect(wallData[i]))) return false;
		  }
		  for (let i = 0; i < boundaryObstacles.length; i++) {
		    const obstacleRect = getRect(boundaryObstacles[i]);
		    if (obstacleRect && rectsOverlap(grieverRect, obstacleRect)) return false;
		  }
		  return true;
		}
		
		function separateCollidingGrievers(a, b) {
		  if (!a || !b) return;
		  const aCenter = getObjectCenter(a);
		  const bCenter = getObjectCenter(b);
		  let dx = bCenter.x - aCenter.x;
		  let dy = bCenter.y - aCenter.y;
		  let distance = Math.sqrt(dx * dx + dy * dy);
		  if (distance < 0.01) {
		    const angle = Math.random() * Math.PI * 2;
		    dx = Math.cos(angle);
		    dy = Math.sin(angle);
		    distance = 1;
		  }
		  const ux = dx / distance;
		  const uy = dy / distance;
		
		  for (let step = 0; step < GRIEVER_PUSH_STEPS; step++) {
		    const aX = a.x - ux * GRIEVER_COLLISION_SEPARATION;
		    const aY = a.y - uy * GRIEVER_COLLISION_SEPARATION;
		    const bX = b.x + ux * GRIEVER_COLLISION_SEPARATION;
		    const bY = b.y + uy * GRIEVER_COLLISION_SEPARATION;
		    if (canPlaceGrieverIgnoringPeers(a, aX, aY)) {
		      a.x = aX;
		      a.y = aY;
		    }
		    if (canPlaceGrieverIgnoringPeers(b, bX, bY)) {
		      b.x = bX;
		      b.y = bY;
		    }
		    if (!grieversCurrentlyOverlap(a, b)) break;
		  }
		}
		
		function getGrieverCollisionCooldown(griever) {
		  return grieverCollisionCooldowns.get(griever) || 0;
		}
		
		function setGrieverCollisionCooldown(griever) {
		  if (griever) grieverCollisionCooldowns.set(griever, GRIEVER_COLLISION_COOLDOWN_TICKS);
		}
		
		function tickGrieverCollisionCooldowns() {
		  grievers.forEach(griever => {
		    const ticks = getGrieverCollisionCooldown(griever);
		    if (ticks > 1) grieverCollisionCooldowns.set(griever, ticks - 1);
		    else if (ticks === 1) grieverCollisionCooldowns.delete(griever);
		
		    const yieldTicks = grieverYieldTicks.get(griever) || 0;
		    if (yieldTicks > 1) grieverYieldTicks.set(griever, yieldTicks - 1);
		    else if (yieldTicks === 1) grieverYieldTicks.delete(griever);
		  });
		}
		
		function setGrieverYield(griever, ticks = GRIEVER_COLLISION_YIELD_TICKS) {
		  if (!griever) return;
		  grieverYieldTicks.set(griever, ticks);
		}
		
		function handleGrieverSoftWallCollision(griever, other) {
		  if (!griever || !other) return false;
		
		  if (getGrieverCollisionCooldown(griever) > 0 || getGrieverCollisionCooldown(other) > 0) {
		    return false;
		  }
		
		  reverseGrieverDirection(griever);
		  reverseGrieverDirection(other);
		  const movingState = grieverPathStates.get(griever);
		  const otherState = grieverPathStates.get(other);
		  if (movingState) movingState.pauseTicks = 0;
		  if (otherState) otherState.pauseTicks = 0;
		  separateCollidingGrievers(griever, other);
		  setGrieverCollisionCooldown(griever);
		  setGrieverCollisionCooldown(other);
		  return false;
		}
		
		function grieversCurrentlyOverlap(a, b) {
		  if (!a || !b || a.visible === false || b.visible === false) return false;
		  const aRect = getGrieverCollisionRectAt(a, a.x, a.y);
		  const bRect = getGrieverCollisionRectAt(b, b.x, b.y);
		  return !!aRect && !!bRect && rectsOverlap(aRect, bRect);
		}
		
		function resolveCurrentGrieverClumps() {
		  for (let i = 0; i < grievers.length; i++) {
		    for (let j = i + 1; j < grievers.length; j++) {
		      const a = grievers[i];
		      const b = grievers[j];
		      if (grieversCurrentlyOverlap(a, b)) {
		        handleGrieverSoftWallCollision(a, b);
		      }
		    }
		  }
		}
		
		function isGrieverBlocked(griever, nx, ny) {
		  const grieverRect = getGrieverCollisionRectAt(griever, nx, ny);
		  if (!grieverRect) return false;
		
		  for (let i = 0; i < wallData.length; i++) {
		    if (rectsOverlap(grieverRect, getWallRect(wallData[i]))) return true;
		  }
		
		  for (let i = 0; i < boundaryObstacles.length; i++) {
		    const obstacleRect = getRect(boundaryObstacles[i]);
		    if (obstacleRect && rectsOverlap(grieverRect, obstacleRect)) return true;
		  }
		
		  if (getBlockingGrieverAt(griever, nx, ny)) return true;
		
		  return false;
		}
		
		const GRIEVER_MOVE_DIRECTIONS = [
		  { x: 1, y: 0 },
		  { x: -1, y: 0 },
		  { x: 0, y: 1 },
		  { x: 0, y: -1 },
		  { x: 0.707, y: 0.707 },
		  { x: -0.707, y: 0.707 },
		  { x: 0.707, y: -0.707 },
		  { x: -0.707, y: -0.707 }
		];
		
		function assignGrieverBehaviors() {
		  grievers.forEach((griever, index) => {
		    if (!griever) return;
		    grieverModes.set(griever, grieverPaths.length ? "path" : "wander");
		    if (grieverPaths.length && !grieverPathStates.has(griever)) {
		      const pathState = createGrieverPathState(griever);
		      if (pathState) grieverPathStates.set(griever, pathState);
		    }
		    if (!grieverPaths.length && !grieverDirections.has(griever)) {
		      pickRandomGrieverDirection(griever);
		    }
		  });
		}
		
		function getOpenGrieverDirections(griever, speed) {
		  return GRIEVER_MOVE_DIRECTIONS.filter(dir => {
		    return !isGrieverBlocked(griever, griever.x + dir.x * speed, griever.y + dir.y * speed);
		  });
		}
		
		function pickRandomGrieverDirection(griever) {
		  const openDirections = getOpenGrieverDirections(griever, GRIEVER_RANDOM_SPEED);
		  const choices = openDirections.length ? openDirections : GRIEVER_MOVE_DIRECTIONS;
		  const direction = choices[Math.floor(Math.random() * choices.length)];
		  grieverDirections.set(griever, {
		    x: direction.x,
		    y: direction.y,
		    turnsUntilChange: 24 + Math.floor(Math.random() * 54)
		  });
		}
		
		function pushGrieverAwayFromWall(griever) {
		  const openDirections = getOpenGrieverDirections(griever, GRIEVER_PUSH_DISTANCE);
		  if (!openDirections.length) return false;
		
		  const direction = openDirections[Math.floor(Math.random() * openDirections.length)];
		  grieverDirections.set(griever, {
		    x: direction.x,
		    y: direction.y,
		    turnsUntilChange: 20 + Math.floor(Math.random() * 45)
		  });
		  return true;
		}
		
		function moveGrieverByVector(griever, stepX, stepY) {
		  const nextX = griever.x + stepX;
		  const nextY = griever.y + stepY;
		  const blockingGriever = getBlockingGrieverAt(griever, nextX, nextY);
		
		  if (blockingGriever) {
		    return handleGrieverSoftWallCollision(griever, blockingGriever);
		  }
		
		  if (!isGrieverBlocked(griever, nextX, nextY)) {
		    griever.x = nextX;
		    griever.y = nextY;
		    return true;
		  }
		
		  let moved = false;
		  const xBlockingGriever = getBlockingGrieverAt(griever, nextX, griever.y);
		  if (xBlockingGriever) {
		    return handleGrieverSoftWallCollision(griever, xBlockingGriever);
		  }
		  if (!isGrieverBlocked(griever, nextX, griever.y)) {
		    griever.x = nextX;
		    moved = true;
		  }
		  const yBlockingGriever = getBlockingGrieverAt(griever, griever.x, nextY);
		  if (yBlockingGriever) {
		    return handleGrieverSoftWallCollision(griever, yBlockingGriever);
		  }
		  if (!isGrieverBlocked(griever, griever.x, nextY)) {
		    griever.y = nextY;
		    moved = true;
		  }
		
		  if (!moved) {
		    const direction = grieverDirections.get(griever);
		    if (direction) {
		      direction.x *= -1;
		      direction.y *= -1;
		      direction.turnsUntilChange = Math.max(direction.turnsUntilChange || 0, 18);
		    } else {
		      pickRandomGrieverDirection(griever);
		    }
		  }
		  return moved;
		}
		
		function moveGrieverByVectorGracefully(griever, stepX, stepY, onBlockedByGriever = null) {
		  const nextX = griever.x + stepX;
		  const nextY = griever.y + stepY;
		  const blockingGriever = getBlockingGrieverAt(griever, nextX, nextY);
		
		  if (blockingGriever) {
		    if (onBlockedByGriever && onBlockedByGriever(blockingGriever)) return true;
		    return handleGrieverSoftWallCollision(griever, blockingGriever);
		  }
		
		  if (!isGrieverBlocked(griever, nextX, nextY)) {
		    griever.x = nextX;
		    griever.y = nextY;
		    return true;
		  }
		
		  return false;
		}
		
		function moveGrieverCenterTo(griever, center) {
		  const currentCenter = getGrieverCenterAt(griever, griever.x, griever.y);
		  const dx = center.x - currentCenter.x;
		  const dy = center.y - currentCenter.y;
		  if (dx * dx + dy * dy > GRIEVER_MAX_PATH_SNAP * GRIEVER_MAX_PATH_SNAP) return false;
		
		  const nextX = griever.x + (center.x - currentCenter.x);
		  const nextY = griever.y + (center.y - currentCenter.y);
		  const blockingGriever = getBlockingGrieverAt(griever, nextX, nextY);
		
		  if (blockingGriever) {
		    return handleGrieverSoftWallCollision(griever, blockingGriever);
		  }
		
		  if (isGrieverBlocked(griever, nextX, nextY)) return false;
		
		  griever.x = nextX;
		  griever.y = nextY;
		  return true;
		}
		
		function tryMoveGrieverInsidePath(griever, path, targetCenter) {
		  if (!path || !targetCenter) return false;
		  const center = clampPointToPath(targetCenter, path);
		  return moveGrieverCenterTo(griever, center);
		}
		
		function getDistanceToPath(point, path) {
		  if (!point || !path) return Infinity;
		  const clamped = clampPointToPath(point, path);
		  const dx = point.x - clamped.x;
		  const dy = point.y - clamped.y;
		  return dx * dx + dy * dy;
		}
		
		function getPathCenter(path) {
		  if (!path?.rect) return { x: 0, y: 0 };
		  return {
		    x: path.rect.x + path.rect.width / 2,
		    y: path.rect.y + path.rect.height / 2
		  };
		}
		
		function getRectDistanceSq(a, b) {
		  if (!a || !b) return Infinity;
		  const dx = Math.max(a.x - (b.x + b.width), b.x - (a.x + a.width), 0);
		  const dy = Math.max(a.y - (b.y + b.height), b.y - (a.y + a.height), 0);
		  return dx * dx + dy * dy;
		}
		
		function getPathForwardPoint(path, direction) {
		  const rect = path?.rect;
		  if (!rect) return null;
		  return path.axis === "x"
		    ? {
		        x: direction >= 0 ? rect.x + rect.width : rect.x,
		        y: rect.y + rect.height / 2
		      }
		    : {
		        x: rect.x + rect.width / 2,
		        y: direction >= 0 ? rect.y + rect.height : rect.y
		      };
		}
		
		function getPathMovementVector(state, currentCenter, speed) {
		  if (!state?.path || !currentCenter) return { x: 0, y: 0 };
		
		  const pathCenter = getPathCenter(state.path);
		  if (state.path.axis === "x") {
		    const correction = Math.max(
		      -GRIEVER_CENTERING_SPEED,
		      Math.min(GRIEVER_CENTERING_SPEED, pathCenter.y - currentCenter.y)
		    );
		    return { x: state.direction * speed, y: correction };
		  }
		
		  const correction = Math.max(
		    -GRIEVER_CENTERING_SPEED,
		    Math.min(GRIEVER_CENTERING_SPEED, pathCenter.x - currentCenter.x)
		  );
		  return { x: correction, y: state.direction * speed };
		}
		
		function getPathDirectionAwayFromPath(path, previousPath, fallbackPoint) {
		  if (!path) return 1;
		  const pathCenter = getPathCenter(path);
		  const previousCenter = previousPath ? getPathCenter(previousPath) : fallbackPoint;
		  const comparePoint = previousCenter || fallbackPoint || pathCenter;
		  const delta = path.axis === "x"
		    ? pathCenter.x - comparePoint.x
		    : pathCenter.y - comparePoint.y;
		  if (Math.abs(delta) > 1) return delta >= 0 ? 1 : -1;
		  return Math.random() < 0.5 ? -1 : 1;
		}
		
		function rememberGrieverPath(state, path) {
		  if (!state || !path) return;
		  state.recentPaths = state.recentPaths || [];
		  state.recentPaths = state.recentPaths.filter(item => item !== path);
		  state.recentPaths.unshift(path);
		  if (state.recentPaths.length > GRIEVER_RECENT_PATH_LIMIT) {
		    state.recentPaths.length = GRIEVER_RECENT_PATH_LIMIT;
		  }
		}
		
		function noteGrieverPathTransition(state, nextPath) {
		  if (!state || !nextPath) return;
		  if (state.lastPath && nextPath === state.lastPath && state.path === state.previousPath) {
		    state.oscillationTurns = (state.oscillationTurns || 0) + 1;
		  } else if (state.previousPath && nextPath === state.previousPath) {
		    state.oscillationTurns = (state.oscillationTurns || 0) + 1;
		  } else {
		    state.oscillationTurns = 0;
		  }
		  state.samePathReversals = 0;
		  state.lastPath = state.path;
		}
		
		function getOscillationDiversionPath(griever, state, targetCenter) {
		  const needsDiversion = state?.forceDiversion ||
		    (state?.oscillationTurns || 0) >= GRIEVER_OSCILLATION_LIMIT ||
		    (state?.samePathReversals || 0) >= GRIEVER_SAME_PATH_REVERSAL_LIMIT;
		  if (!state?.path || !needsDiversion) return null;
		
		  const currentCenter = getGrieverCenterAt(griever, griever.x, griever.y);
		  const allNeighbors = getPathNeighbors(state.path);
		  const freshNeighbors = allNeighbors.filter(path =>
		    path !== state.previousPath &&
		    path !== state.lastPath &&
		    !(state.recentPaths || []).includes(path)
		  );
		  const nonPreviousNeighbors = allNeighbors.filter(path => path !== state.previousPath);
		  const pool = freshNeighbors.length
		    ? freshNeighbors
		    : (nonPreviousNeighbors.length ? nonPreviousNeighbors : allNeighbors);
		  const neighbors = pool.sort((a, b) => {
		      const target = targetCenter || currentCenter;
		      const aTarget = getDistanceToPath(target, a);
		      const bTarget = getDistanceToPath(target, b);
		      if (aTarget !== bTarget) return aTarget - bTarget;
		      return getDistanceToPath(currentCenter, a) - getDistanceToPath(currentCenter, b);
		    });
		
		  const shortlist = neighbors.slice(0, Math.min(2, neighbors.length));
		  return shortlist.length ? shortlist[Math.floor(Math.random() * shortlist.length)] : null;
		}
		
		function pickPathCandidate(candidates, state) {
		  if (!candidates.length) return null;
		
		  const nonPrevious = candidates.filter(path => path !== state.previousPath);
		  const pool = nonPrevious.length ? nonPrevious : candidates;
		
		  const nonRecent = pool.filter(path => !(state.recentPaths || []).includes(path));
		  const preferred = nonRecent.length ? nonRecent : pool;
		  const shortlist = preferred.slice(0, Math.min(3, preferred.length));
		
		  return shortlist[Math.floor(Math.random() * shortlist.length)];
		}
		
		function chooseNextPath(griever, state, targetCenter) {
		  if (!state?.path) return null;
		
		  const currentCenter = getGrieverCenterAt(griever, griever.x, griever.y);
		  if (state.forcedReturnPath) {
		    const returnPath = state.forcedReturnPath;
		    const isNeighbor = getPathNeighbors(state.path).includes(returnPath);
		    const returnCenter = clampPointToPath(currentCenter, returnPath);
		    if (isNeighbor && tryMoveGrieverInsidePath(griever, returnPath, returnCenter)) {
		      state.forcedReturnPath = null;
		      state.collisionRetreatTicks = 0;
		      return returnPath;
		    }
		    if (!isNeighbor) state.forcedReturnPath = null;
		  }
		
		  const diversionPath = getOscillationDiversionPath(griever, state, targetCenter);
		  if (diversionPath) {
		    const diversionCenter = clampPointToPath(currentCenter, diversionPath);
		    if (tryMoveGrieverInsidePath(griever, diversionPath, diversionCenter)) {
		      state.forceDiversion = false;
		      state.oscillationTurns = 0;
		      state.samePathReversals = 0;
		      state.recentPaths = [diversionPath];
		      return diversionPath;
		    }
		  }
		
		  const forwardPoint = getPathForwardPoint(state.path, state.direction) || currentCenter;
		  const neighbors = getPathNeighbors(state.path)
		    .sort((a, b) => {
		      const aForwardDistance = getDistanceToPath(forwardPoint, a);
		      const bForwardDistance = getDistanceToPath(forwardPoint, b);
		      if (aForwardDistance !== bForwardDistance) return aForwardDistance - bForwardDistance;
		      const aTargetDistance = getDistanceToPath(targetCenter, a);
		      const bTargetDistance = getDistanceToPath(targetCenter, b);
		      if (aTargetDistance !== bTargetDistance) return aTargetDistance - bTargetDistance;
		      const aDistance = getDistanceToPath(currentCenter, a);
		      const bDistance = getDistanceToPath(currentCenter, b);
		      return aDistance - bDistance;
		    });
		
		  if (!neighbors.length) return null;
		
		  while (neighbors.length) {
		    const nextPath = pickPathCandidate(neighbors, state);
		    if (!nextPath) return null;
		    const nextCenter = clampPointToPath(currentCenter, nextPath);
		    if (tryMoveGrieverInsidePath(griever, nextPath, nextCenter)) {
		      return nextPath;
		    }
		    neighbors.splice(neighbors.indexOf(nextPath), 1);
		  }
		
		  return null;
		}
		
		function recoverStuckPathGriever(griever, state, targetPoint) {
		  if (!griever || !state?.path) return;
		
		  const currentCenter = getGrieverCenterAt(griever, griever.x, griever.y);
		  const neighbors = getPathNeighbors(state.path)
		    .filter(path => path !== state.previousPath)
		    .sort((a, b) => {
		      const target = targetPoint || currentCenter;
		      const aDistance = getDistanceToPath(target, a);
		      const bDistance = getDistanceToPath(target, b);
		      if (aDistance !== bDistance) return aDistance - bDistance;
		      return getDistanceToPath(currentCenter, a) - getDistanceToPath(currentCenter, b);
		    });
		
		  while (neighbors.length) {
		    const nextPath = neighbors.shift();
		    const nextCenter = clampPointToPath(currentCenter, nextPath);
		    if (tryMoveGrieverInsidePath(griever, nextPath, nextCenter)) {
		      const previousPath = state.path;
		      state.previousPath = previousPath;
		      noteGrieverPathTransition(state, nextPath);
		      state.path = nextPath;
		      state.direction = getPathDirectionAwayFromPath(nextPath, previousPath, currentCenter);
		      state.recentPaths = [nextPath];
		      state.stuckTicks = 0;
		      return;
		    }
		  }
		
		  reversePathState(state);
		  state.recentPaths = [state.path];
		  state.stuckTicks = 0;
		}
		
		function trackPathGrieverProgress(griever, state, targetPoint) {
		  if (!griever || !state) return;
		
		  const lastX = state.lastX;
		  const lastY = state.lastY;
		  state.lastX = griever.x;
		  state.lastY = griever.y;
		
		  if (lastX == null || lastY == null) {
		    state.stuckTicks = 0;
		    return;
		  }
		
		  const dx = griever.x - lastX;
		  const dy = griever.y - lastY;
		  if (dx * dx + dy * dy >= GRIEVER_STUCK_MOVE_EPS * GRIEVER_STUCK_MOVE_EPS) {
		    state.stuckTicks = 0;
		    return;
		  }
		
		  state.stuckTicks = (state.stuckTicks || 0) + 1;
		  if (state.stuckTicks >= GRIEVER_STUCK_TICKS) {
		    recoverStuckPathGriever(griever, state, targetPoint);
		    state.lastX = griever.x;
		    state.lastY = griever.y;
		  }
		}
		
		function updatePathGriever(griever, targetPoint) {
		  let state = grieverPathStates.get(griever);
		  if (!state) {
		    state = createGrieverPathState(griever);
		    if (!state) return null;
		    grieverPathStates.set(griever, state);
		  }
		
		  if (state.pauseTicks > 0) {
		    state.pauseTicks--;
		    trackPathGrieverProgress(griever, state, targetPoint);
		    return state;
		  }
		
		  const speed = targetPoint ? GRIEVER_SPEED : GRIEVER_RANDOM_SPEED;
		  const currentCenter = getGrieverCenterAt(griever, griever.x, griever.y);
		
		  if (!pointInRect(currentCenter, state.path.rect, GRIEVER_PATH_JOIN_PAD)) {
		    const clampedCenter = clampPointToPath(currentCenter, state.path);
		    const dx = clampedCenter.x - currentCenter.x;
		    const dy = clampedCenter.y - currentCenter.y;
		    const distance = Math.sqrt(dx * dx + dy * dy) || 1;
		    if (moveGrieverByVectorGracefully(griever, (dx / distance) * speed, (dy / distance) * speed)) {
		      if (state.collisionRetreatTicks > 0) state.collisionRetreatTicks--;
		      trackPathGrieverProgress(griever, state, targetPoint);
		      return state;
		    }
		    if (state.collisionRetreatTicks > 0) {
		      state.collisionRetreatTicks--;
		      trackPathGrieverProgress(griever, state, targetPoint);
		      return state;
		    }
		    reversePathState(state);
		    trackPathGrieverProgress(griever, state, targetPoint);
		    return state;
		  }
		
		  const targetCenter = {
		    x: currentCenter.x + (state.path.axis === "x" ? state.direction * speed : 0),
		    y: currentCenter.y + (state.path.axis === "y" ? state.direction * speed : 0)
		  };
		
		  if (pointInRect(targetCenter, state.path.rect, 0)) {
		    const moveVector = getPathMovementVector(state, currentCenter, speed);
		    if (moveGrieverByVectorGracefully(
		      griever,
		      moveVector.x,
		      moveVector.y
		    )) {
		      if (state.collisionRetreatTicks > 0) state.collisionRetreatTicks--;
		      trackPathGrieverProgress(griever, state, targetPoint);
		      return state;
		    }
		
		    if (state.collisionRetreatTicks > 0) {
		      state.collisionRetreatTicks--;
		      trackPathGrieverProgress(griever, state, targetPoint);
		      return state;
		    }
		
		    const blockedNextPath = chooseNextPath(griever, state, targetPoint || targetCenter);
		    if (blockedNextPath) {
		      const previousPath = state.path;
		      state.previousPath = previousPath;
		      noteGrieverPathTransition(state, blockedNextPath);
		      state.path = blockedNextPath;
		      state.direction = getPathDirectionAwayFromPath(blockedNextPath, previousPath, currentCenter);
		      rememberGrieverPath(state, blockedNextPath);
		      trackPathGrieverProgress(griever, state, targetPoint);
		      return state;
		    }
		
		    reversePathState(state);
		    trackPathGrieverProgress(griever, state, targetPoint);
		    return state;
		  }
		
		  const nextPath = chooseNextPath(griever, state, targetPoint || targetCenter);
		  if (nextPath) {
		    const previousPath = state.path;
		    state.previousPath = previousPath;
		    noteGrieverPathTransition(state, nextPath);
		    state.path = nextPath;
		    state.direction = getPathDirectionAwayFromPath(nextPath, previousPath, currentCenter);
		    rememberGrieverPath(state, nextPath);
		    trackPathGrieverProgress(griever, state, targetPoint);
		    return state;
		  }
		
		  reversePathState(state);
		  const reverseTarget = {
		    x: currentCenter.x + (state.path.axis === "x" ? state.direction * speed : 0),
		    y: currentCenter.y + (state.path.axis === "y" ? state.direction * speed : 0)
		  };
		
		  tryMoveGrieverInsidePath(griever, state.path, reverseTarget);
		
		  trackPathGrieverProgress(griever, state, targetPoint);
		  return state;
		}
		
		function updateChasingGriever(griever, avatarCenter) {
		  const grieverCenter = getObjectCenter(griever);
		  const dx = avatarCenter.x - grieverCenter.x;
		  const dy = avatarCenter.y - grieverCenter.y;
		  const distance = Math.sqrt(dx * dx + dy * dy) || 1;
		  const moved = moveGrieverByVector(
		    griever,
		    (dx / distance) * GRIEVER_SPEED,
		    (dy / distance) * GRIEVER_SPEED
		  );
		
		  if (!moved) pickRandomGrieverDirection(griever);
		  return distance;
		}
		
		function updateWanderingGriever(griever) {
		  let direction = grieverDirections.get(griever);
		  const retreating = (direction?.collisionRetreatTicks || 0) > 0;
		  if (!direction || (!retreating && (direction.turnsUntilChange <= 0 || Math.random() < 0.015))) {
		    pickRandomGrieverDirection(griever);
		    direction = grieverDirections.get(griever);
		  }
		
		  const moved = moveGrieverByVector(
		    griever,
		    direction.x * GRIEVER_RANDOM_SPEED,
		    direction.y * GRIEVER_RANDOM_SPEED
		  );
		
		  if (moved) {
		    direction.turnsUntilChange--;
		    if (direction.collisionRetreatTicks > 0) direction.collisionRetreatTicks--;
		  } else if (direction.collisionRetreatTicks > 0) {
		    direction.collisionRetreatTicks--;
		  } else {
		    pickRandomGrieverDirection(griever);
		  }
		
		  return direction;
		}
		
		// ====================== SMART PATH CHASE ======================
		// When a griever is within chase radius it continuously re-evaluates which
		// path rectangle is closest to the avatar and snaps its state onto that path,
		// then drives along it toward the avatar.  This makes grievers actively hunt
		// the avatar through the maze network instead of wandering their current path.
		
		function getNearestPathToAvatar(avatarCenter) {
		  if (!grieverPaths.length || !avatarCenter) return null;
		  let bestPath = null;
		  let bestDist = Infinity;
		  grieverPaths.forEach(path => {
		    const clamped = clampPointToPath(avatarCenter, path);
		    const dx = avatarCenter.x - clamped.x;
		    const dy = avatarCenter.y - clamped.y;
		    const d  = dx * dx + dy * dy;
		    if (d < bestDist) { bestDist = d; bestPath = path; }
		  });
		  return bestPath;
		}
		
		// Ensures the griever's path state is steering toward the path rect nearest
		// to the avatar. If the griever is already on an adjacent path it just
		// updates direction; otherwise it migrates to the nearest reachable path
		// that is closer to the avatar than the current one.
		function snapGrieverTowardAvatar(griever, state, avatarCenter) {
		  if (!state || !avatarCenter || !grieverPaths.length) return;
		
		  const targetPath = getNearestPathToAvatar(avatarCenter);
		  if (!targetPath || targetPath === state.path) {
		    // Already on the best path — just aim direction toward avatar
		    return;
		  }
		
		  // If the target path is a direct neighbour, steer toward it naturally
		  const neighbors = getPathNeighbors(state.path);
		  if (neighbors.includes(targetPath)) {
		    return;
		  }
		
		  // Find the path nearest to the griever itself; if it is closer to the
		  // avatar than the current path, switch onto it to close the gap
		  const grieverCenter = getGrieverCenterAt(griever, griever.x, griever.y);
		  const nearestToSelf = getNearestPathToPoint(grieverCenter);
		  const currentNeighbors = getPathNeighbors(state.path);
		
		  const recentlyVisited = state.recentPaths || [];
		  if (nearestToSelf &&
		      nearestToSelf !== state.path &&
		      currentNeighbors.includes(nearestToSelf) &&
		      nearestToSelf !== state.previousPath &&
		      !recentlyVisited.includes(nearestToSelf)) {
		    const distCurrent = getDistanceToPath(avatarCenter, state.path);
		    const distNearest = getDistanceToPath(avatarCenter, nearestToSelf);
		    if (distNearest < distCurrent) {
		      const previousPath = state.path;
		      state.previousPath = previousPath;
		      noteGrieverPathTransition(state, nearestToSelf);
		      state.path         = nearestToSelf;
		      state.direction    = getPathDirectionAwayFromPath(nearestToSelf, previousPath, grieverCenter);
		      rememberGrieverPath(state, nearestToSelf);
		    }
		  }
		}
		
		function updateGrievers() {
		  if (answerFeedbackResetting) return;
		  if ((gameState !== "PLAYING" && gameState !== "QUESTION") || !avatar) return;
		
		  tickGrieverCollisionCooldowns();
		  resolveCurrentGrieverClumps();
		  const avatarCenter = getObjectCenter(avatar);
		
		  grievers.forEach((griever, index) => {
		    if (!griever || griever.visible === false) return;
		
		    const grieverCenterBeforeMove = getObjectCenter(griever);
		    const distanceBeforeMove = Math.sqrt(
		      Math.pow(avatarCenter.x - grieverCenterBeforeMove.x, 2) +
		      Math.pow(avatarCenter.y - grieverCenterBeforeMove.y, 2)
		    ) || 1;
		
		    const mode = grieverModes.get(griever) || (grieverPaths.length ? "path" : "wander");
		    const isChasing = distanceBeforeMove <= GRIEVER_CHASE_RADIUS;
		
		    if (isChasing && mode === "path") {
		      // KEY: each tick, migrate the griever's active path to whichever
		      // rectangle is nearest to the avatar so it hunts purposefully
		      let state = grieverPathStates.get(griever);
		      if (!state) {
		        state = createGrieverPathState(griever);
		        if (state) grieverPathStates.set(griever, state);
		      }
		      if (state) snapGrieverTowardAvatar(griever, state, avatarCenter);
		      updatePathGriever(griever, avatarCenter);
		
		    } else if (isChasing) {
		      // No path data — fall back to direct vector chase
		      updateChasingGriever(griever, avatarCenter);
		
		    } else if (mode === "path") {
		      // Outside chase radius — wander along paths normally
		      updatePathGriever(griever);
		
		    } else if (mode === "chase") {
		      updateChasingGriever(griever, avatarCenter);
		
		    } else {
		      updateWanderingGriever(griever);
		    }
		
		    const grieverCenter = getObjectCenter(griever);
		    const distance = Math.sqrt(
		      Math.pow(avatarCenter.x - grieverCenter.x, 2) +
		      Math.pow(avatarCenter.y - grieverCenter.y, 2)
		    ) || 1;
		
		    if (objectsOverlap(griever, avatar) || distance <= GRIEVER_CONTACT_PAD) {
		      handleGrieverContact(griever);
		    }
		  });
		}
		
		createjs.Ticker.addEventListener("tick", updateGrievers);
		
