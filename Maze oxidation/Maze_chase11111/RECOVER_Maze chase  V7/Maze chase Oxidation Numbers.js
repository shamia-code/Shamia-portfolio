		// Two bugs fixed:
		// 1. Correct path: was adding qIndex (number) to `answered` but checkpoint
		//    checks answered.has(cp.id) (string like "cp1"). Fixed to add cp.id.
		// 2. Wrong path: after feedback clears, answerCollisionArmed was not reset,
		//    so the collision system never re-armed for the next attempt. Fixed to
		//    reset answerCollisionArmed = false after the wrong-answer cooldown.
		
		function handleAnswer(chosen) {
		  if (gameState !== "QUESTION" || questionLocked) return;
		  questionLocked = true;
		  stopMoving();
		  const q  = questions[questionPanel.qIndex];
		  const currentCpId = questionPanel.cpID;
		  const chosenOpt = getAnswerOption(chosen);
		  const knockedTarget = knockAnswerTarget(chosen);
		  beginAnswerFeedbackReset();
		
		  if (chosen === q.c) {
		    disableAllOptions();
		    updateFeedbackDisplay("\u2713 " + q.ok, "#134937");
		    playFeedbackSound("correct");
		
		    // FIX 1: add the checkpoint id (string) so answered.has(cp.id) works correctly
		    answered.add(currentCpId);
		    score += 10;
		    updateScoreDisplay();
		
		    const nextQuestionIndex = questionPanel.qIndex + 1;
		    const isLastQuestion = nextQuestionIndex >= questions.length;
		
		    setTimeout(() => {
		      questionPanel.visible = false;
		
		      if (isLastQuestion) {
		        endAnswerFeedbackReset(true, () => {
		          if (timerInterval) clearInterval(timerInterval);
		          if (moveInterval)  clearInterval(moveInterval);
		          timerInterval = null;
		          moveInterval  = null;
		          triggerWin();
		        });
		        return;
		      }
		
		      // Advance checkpoint index and show next question
		      currentCheckpointIndex = nextQuestionIndex;
		      endAnswerFeedbackReset(true, () => {
		        setTimeout(() => {
		          showQuestion(nextQuestionIndex, checkpoints[nextQuestionIndex]?.id || "q" + (nextQuestionIndex + 1));
		        }, 300);
		      });
		    }, ANSWER_FEEDBACK_MS);
		
		  } else {
		    loseLife("Wrong answer", true);
		    updateFeedbackDisplay("\u2717 " + q.bad, "#741313");
		    playFeedbackSound("wrong");
		    if (lives <= 0) {
		      setTimeout(() => {
		        endAnswerFeedbackReset(true, () => {
		          triggerFailed("3 wrong answers on one question");
		        });
		      }, ANSWER_FEEDBACK_MS);
		    } else {
		      const wrongTarget = knockedTarget || chosenOpt;
		      if (wrongTarget) {
		        wrongTarget.mouseEnabled = false;
		        setTimeout(() => {
		          if (wrongTarget) {
		            restoreDisplayObjectStanding(wrongTarget);
		            wrongTarget.mouseEnabled = false;
		          }
		          updateFeedbackDisplay(INITIAL_FEEDBACK_TEXT, null);
		          endAnswerFeedbackReset(true, () => {
		            questionLocked = false;
		            // FIX 2: reset arm state so the collision system re-arms for the next attempt
		            answerCollisionArmed = false;
		            optionContactLocks.clear();
		            refreshAnswerContactLocks();
		          });
		        }, ANSWER_FEEDBACK_MS);
		      } else {
		        endAnswerFeedbackReset(true, () => {
		          questionLocked = false;
		          // FIX 2 (fallback path): same reset
		          answerCollisionArmed = false;
		          optionContactLocks.clear();
		        });
		      }
		    }
		  }
		}
		
