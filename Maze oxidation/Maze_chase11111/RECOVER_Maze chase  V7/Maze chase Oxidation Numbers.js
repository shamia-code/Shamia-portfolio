		  if (!obj) return;
		  createjs.Tween.get(obj, { loop: true })
		    .to({ scaleX: maxScale, scaleY: maxScale, alpha: 0.85 }, speed, createjs.Ease.sineInOut)
		    .to({ scaleX: 1,        scaleY: 1,        alpha: 1    }, speed, createjs.Ease.sineInOut);
