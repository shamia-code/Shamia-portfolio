		// ====================== MOVEMENT ======================
		function moveAvatarStep(dx, dy) {
		  if (!avatar || (gameState !== "PLAYING" && gameState !== "QUESTION")) return false;
		
		  const targetX = avatar.x + dx;
		  const targetY = avatar.y + dy;
		  let moved = false;
		
		  if (dx !== 0) {
		    if (!isCollidingWithAnyWall(targetX, avatar.y)) {
		      avatar.x = targetX;
		      moved = true;
		    } else {
		      stopMoving();
		      return false;
		    }
		  }
		
		  if (dy !== 0) {
		    if (!isCollidingWithAnyWall(avatar.x, targetY)) {
		      avatar.y = targetY;
		      moved = true;
		    } else {
		      stopMoving();
		      return false;
		    }
		  }
		
		  checkAnswerCollision();
		  checkExitCollision();
		  return moved;
		}
		
		function startMoving(dx, dy) {
		  if (gameState !== "PLAYING" && gameState !== "QUESTION") return;
		  if (moveInterval) clearInterval(moveInterval);
		  moveInterval = setInterval(() => {
		    if (gameState !== "PLAYING" && gameState !== "QUESTION") return;
		    moveAvatarStep(dx, dy);
		  }, 50);
		  moveAvatarStep(dx, dy);
		}
		
		function stopMoving() {
		  if (moveInterval) clearInterval(moveInterval);
		  moveInterval = null;
		}
		
