		function getNamedDescendantByExactName(container, targetName) {
		  if (!container) return null;
		  if (String(container.name || "").toLowerCase() === targetName.toLowerCase()) return container;
		
		  const namedChildren = [];
		  collectNamedDescendants(container, namedChildren, new Set());
		  return namedChildren.find(child => String(child?.name || "").toLowerCase() === targetName.toLowerCase()) || null;
		}
		
		function getNamedDescendantsByExactName(container, targetName) {
		  if (!container) return [];
		
		  const target = targetName.toLowerCase();
		  const matches = [];
		  if (String(container.name || "").toLowerCase() === target) matches.push(container);
		
		  const namedChildren = [];
		  collectNamedDescendants(container, namedChildren, new Set());
		  namedChildren.forEach(child => {
		    if (String(child?.name || "").toLowerCase() === target) matches.push(child);
		  });
		
		  return matches;
		}
		
