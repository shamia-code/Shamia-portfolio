		var ION_CHARGE = {"Hydrogen": 1, "Sodium": 1, "Copper": 2, "Calcium": 2, "Iron3": 3, "Aluminium": 3, "Iron2": 2, "Magnesium": 2, "Hydroxide": 1, "Nitric": 1, "Carbonate": 2, "Oxide": 2, "Phosphate": 3, "Sulphide": 2, "Chloride": 1, "Sulphate": 2};
		var JIGSAW_PITCH = 30 * 1.57341003417969;
		function layoutJigsaw() {
		    var cats = active.filter(function (p) { return p.placed && p.kind === "cation"; });
		    var ans = active.filter(function (p) { return p.placed && p.kind === "anion"; });
		    if ((!cats.length && !ans.length) || !root.Target) return;
		    var catCharge = ION_CHARGE[selectedCation] || ION_CHARGE[selectedAnion] || 1;
		    var anCharge = ION_CHARGE[selectedAnion] || catCharge;
		    function gcd(a, b) { return b ? gcd(b, a % b) : a; }
		    var totalCharge = catCharge * anCharge / gcd(catCharge, anCharge);
		    function prepare(p) {
		        if (p.alignedJigsaw) return;
		        var Ctor = findLibCtor(root["prototypeAligned" + p.name]);
		        if (!Ctor) throw new Error("Missing aligned jigsaw symbol: " + p.name);
		        var replacement = new Ctor();
		        var parent = p.mc.parent || root;
		        parent.removeChild(p.mc);
		        parent.addChild(replacement);
		        p.mc = replacement;
		        p.isStamp = true;
		        p.alignedJigsaw = true;
		        replacement.visible = true;
		        replacement.alpha = 1;
		        replacement.mouseEnabled = true;
		        replacement.scaleX = 1;
		        var localPitch = p.name === "Aluminium" || p.name === "Iron3" ? 30 : 46;
		        replacement.scaleY = JIGSAW_PITCH / localPitch;
		        bindStampDrag(p);
		    }
		    function place(list, charge, x) {
		        var slots = totalCharge / charge;
		        list.forEach(function (p, i) {
		            prepare(p);
		            var slot = slots === 3 && i < 3 ? [1, 0, 2][i] : i;
		            p.mc.x = x;
		            p.mc.y = root.Target.y + (slot - (slots - 1) / 2) * charge * JIGSAW_PITCH;
		        });
		    }
		    place(cats, catCharge, root.Target.x - 48);
		    place(ans, anCharge, root.Target.x + 45);
		    if (root.hint_text && root.hint_text.visible) setHintVisible(true);
		}
		
		function findLibCtor(tpl) {
			if (!tpl) return null;
			if (typeof lib !== "undefined") {
				for (var key in lib) {
					if (!lib.hasOwnProperty(key)) continue;
					var Ctor = lib[key];
					if (typeof Ctor !== "function") continue;
					try { if (tpl instanceof Ctor) return Ctor; } catch (e) {}
				}
			}
			var proto = Object.getPrototypeOf(tpl);
			var C = proto && proto.constructor;
			if (typeof createjs !== "undefined") {
				if (C && C !== createjs.MovieClip && C !== createjs.Container && C !== createjs.DisplayObject) {
					return C;
				}
			} else if (C && C !== Object) {
				return C;
			}
			return null;
		}
		function cloneTemplate(name) {
			var tpl = templates[name];
			if (!tpl) return null;
			var copy = null;
			var Ctor = findLibCtor(tpl);
			if (Ctor) {
				try { copy = new Ctor(); } catch (e) { copy = null; }
			}
			if (!copy && typeof tpl.clone === "function") {
				try { copy = tpl.clone(true); } catch (e2) { copy = null; }
			}
			if (!copy) return null;
			copy.visible = true;
			copy.mouseEnabled = true;
			copy.mouseChildren = false;
			copy.alpha = 1;
			copy.scaleX = tpl.scaleX;
			copy.scaleY = tpl.scaleY;
			copy.rotation = tpl.rotation;
			(tpl.parent || root).addChild(copy);
			return copy;
		}
