		// ---------------------------------------------------------------
		// 7. ZONE HIT-TESTING (circular, based on target bounds — more
		// forgiving than pixel hitTest, and matches irregular pin artwork)
		// ---------------------------------------------------------------
		function getZoneBounds(zone) {
		    var b = zone.getBounds();
		    if (!b) return null;
		    var topLeft     = zone.localToLocal(b.x, b.y, root);
		    var bottomRight = zone.localToLocal(b.x + b.width, b.y + b.height, root);
		    var left   = Math.min(topLeft.x, bottomRight.x);
		    var right  = Math.max(topLeft.x, bottomRight.x);
		    var top    = Math.min(topLeft.y, bottomRight.y);
		    var bottom = Math.max(topLeft.y, bottomRight.y);
		    var width  = right - left;
		    var height = bottom - top;
		    return {
		        centerX: left + width / 2,
		        centerY: top + height / 2,
		        radius:  Math.max(width, height) * 0.5
		    };
		}
		
		function isOverZone(mx, my, zoneBounds) {
		    var dx = mx - zoneBounds.centerX;
		    var dy = my - zoneBounds.centerY;
		    return Math.sqrt(dx * dx + dy * dy) <= zoneBounds.radius;
		}
		
		// ---------------------------------------------------------------
		// 8. DRAG HANDLERS — fresh named functions per index so they can
		// be individually detached once a metal is locked in place
		// ---------------------------------------------------------------
		var pressHandlers = [], moveHandlers = [], releaseHandlers = [];
		
		function buildHandlers(index) {
		    pressHandlers[index] = function (evt) { onPress(evt, index); };
		    moveHandlers[index]  = function (evt) { onDrag(evt, index); };
		    releaseHandlers[index] = function (evt) { onRelease(evt, index); };
		}
		
		function attachEvents(index) {
		    var label = textSymbols[index];
		    if (!label) return;
		    label.addEventListener("mousedown", pressHandlers[index]);
		    label.addEventListener("pressmove", moveHandlers[index]);
		    label.addEventListener("pressup", releaseHandlers[index]);
		}
		
		function detachEvents(index) {
		    var label = textSymbols[index];
		    if (!label) return;
		    label.removeEventListener("mousedown", pressHandlers[index]);
		    label.removeEventListener("pressmove", moveHandlers[index]);
		    label.removeEventListener("pressup", releaseHandlers[index]);
		    label.cursor = "default";
		}
		
		for (var i = 0; i < textSymbols.length; i++) {
		    if (!textSymbols[i]) continue;
		    buildHandlers(i);
		    attachEvents(i);
		}
		
		function onPress(evt, index) {
		    var label = textSymbols[index];
		    if (!label || label.matched) return;
		
		    activeIndex = index;
		    isDragging = true;
		    lineStartX = label.x;
		    lineStartY = label.y;
		
		    var p = root.globalToLocal(evt.stageX, evt.stageY);
		    currentMouseX = p.x;
		    currentMouseY = p.y;
		}
		
		function onDrag(evt, index) {
		    if (!isDragging || activeIndex !== index) return;
		    var p = root.globalToLocal(evt.stageX, evt.stageY);
		    currentMouseX = p.x;
		    currentMouseY = p.y;
		}
		
		function onRelease(evt, index) {
		    if (!isDragging || activeIndex !== index) return;
		    isDragging = false;
		
		    var p = root.globalToLocal(evt.stageX, evt.stageY);
		    currentMouseX = p.x;
		    currentMouseY = p.y;
		
		    var label = textSymbols[index];
		
		    var dropIndex = -1;
		    for (var k = 0; k < targets.length; k++) {
		        if (targetUsed[k] || !targets[k]) continue;
		        var bounds = getZoneBounds(targets[k]);
		        if (bounds && isOverZone(currentMouseX, currentMouseY, bounds)) {
		            dropIndex = k;
		            break;
		        }
		    }
		
		    if (dropIndex === -1) {
		        // dropped on empty space or an already-completed pin: refuse silently
		        activeIndex = -1;
		        return;
		    }
		
		    if (targetCategory[dropIndex] === label.category) {
		        handleCorrect(index, dropIndex);
		    } else {
		        handleIncorrect(dropIndex);
		    }
		
		    activeIndex = -1;
		}
		
		// ---------------------------------------------------------------
		// 9. CORRECT / INCORRECT RESULTS
		// ---------------------------------------------------------------
		function handleCorrect(labelIndex, dropIndex) {
		    targetUsed[dropIndex] = true;
		    var label = textSymbols[labelIndex];
		    label.matched = true;
		    detachEvents(labelIndex);
		    label.alpha = 0.5;
		
		    var bounds = getZoneBounds(targets[dropIndex]);
		    permanentLines.push({
		        x1: lineStartX, y1: lineStartY,
		        x2: bounds.centerX, y2: bounds.centerY,
		        color: lineColors[labelIndex]
		    });
		
		    if (ticks[dropIndex]) ticks[dropIndex].visible = true;
		    createjs.Sound.play("ding");
		
		    correctCount++;
		    if (correctCount === textSymbols.filter(function (t) { return !!t; }).length) {
		        onAllCorrect();
		    }
		}
		
		function handleIncorrect(dropIndex) {
		    wrongCount++;
		
		    if (crosses[dropIndex]) {
		        crosses[dropIndex].visible = true;
		        // capture the cross reference for the closure below
		        (function (crossRef) {
		            setTimeout(function () {
		                crossRef.visible = false;
		            }, 1000);
		        })(crosses[dropIndex]);
		    }
		
		    createjs.Sound.play("buzz");
		
		    if (wrongCount >= 3 && hintBtn) {
		        hintBtn.visible = true;
		    }
		}
		
